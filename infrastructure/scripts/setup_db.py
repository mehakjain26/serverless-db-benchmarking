import os
import aurora_dsql_psycopg2 as dsql

# Fetch DSQL configuration from environment variables
DSQL_ENDPOINT = os.environ.get("DSQL_ENDPOINT")
DB_REGION = os.environ.get("DB_REGION", "us-east-1")


TABLES = [

"""
CREATE TABLE IF NOT EXISTS stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY,
    transport_id INT,
    gtfs_stop_id TEXT,
    stop_name TEXT,
    stop_lat DOUBLE PRECISION,
    stop_lon DOUBLE PRECISION,
    location_type SMALLINT,
    parent_station TEXT
)
""",

"""
CREATE TABLE IF NOT EXISTS routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY,
    transport_id INT,
    gtfs_route_id TEXT,
    route_short_name TEXT,
    route_long_name TEXT,
    route_type SMALLINT,
    route_color TEXT
)
""",

"""
CREATE TABLE IF NOT EXISTS calendar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY,
    transport_id INT,
    gtfs_service_id TEXT,
    monday BOOLEAN,
    tuesday BOOLEAN,
    wednesday BOOLEAN,
    thursday BOOLEAN,
    friday BOOLEAN,
    saturday BOOLEAN,
    sunday BOOLEAN,
    start_date TEXT,
    end_date TEXT
)
""",

"""
CREATE TABLE IF NOT EXISTS trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY,
    transport_id INT,
    gtfs_trip_id TEXT,
    gtfs_route_id TEXT,
    gtfs_service_id TEXT,
    trip_headsign TEXT,
    direction_id SMALLINT
)
""",

"""
CREATE TABLE IF NOT EXISTS stop_times (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY,
    transport_id INT,
    gtfs_trip_id TEXT,
    gtfs_stop_id TEXT,
    arrival_time INT,
    departure_time INT,
    stop_sequence INT,
    pickup_type SMALLINT,
    drop_off_type SMALLINT
)
"""

]

def main():
    if not DSQL_ENDPOINT:
        print("Error: DSQL_ENDPOINT environment variable not set.")
        return

    conn = dsql.connect(
        host=DSQL_ENDPOINT,
        region=DB_REGION,
        user="admin"
    )
    conn.autocommit = True
    cur = conn.cursor()

    for sql in TABLES:
        print("Running:", sql.split("(")[0])
        cur.execute(sql)

    cur.close()

    conn.close()

    print("All tables created successfully!")

if __name__ == "__main__":
    main()